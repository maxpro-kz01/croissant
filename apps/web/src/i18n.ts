const dicts: Record<Lang, Dict> = { ru, kk };

export function tr(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? dicts.ru[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export const money = (n: number) => `${Math.round(n).toLocaleString('ru-RU').replace(/ /g, ' ')} ₸`;

/** Название поля из меню на нужном языке (kk с запасным ru) */
export function pick<T extends Record<string, any>>(lang: Lang, obj: T, field: string): string {
  const v = lang === 'kk' ? obj[`${field}_kk`] : obj[`${field}_ru`];
  return v || obj[`${field}_ru`] || '';
}
